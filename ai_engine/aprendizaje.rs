fn main() {
    println!("Hello, world!");
    //Hacemos una variable, donde impirmimos espacios de lineas 20 veces, como esta en el argumento de repeat, depues imprimimos el valor de la variable con {}
    //y luego adjuntamos la variable, ripo c#     
    let espacios = "<<>><<>> aloHola <<>><<>>\n".repeat(15);
    println!("Esto es un espacio: ");
    println!("{}", espacios);
    println!("Pruebas");
}

